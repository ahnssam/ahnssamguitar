-- 악보요청 게시판 (requests.html): 글(sheet_requests) + 댓글(sheet_request_comments) + 좋아요(sheet_request_likes).
-- 읽기는 누구나, 쓰기는 로그인한 사람, 고치기·지우기는 본인 또는 운영 계정(public.is_site_admin()).
-- 작성자 닉네임은 profiles(nickname) 를 붙여 읽는다 (user_id → profiles.id). 운영 계정 글·댓글은 화면에 '안쌤 (관리자)'.
-- 글 상태(요청됨/작업 중/올림)와 공지(맨 위 고정)는 운영 계정만 바꾼다 — 트리거가 막는다.
-- by_admin 은 운영 계정이 쓴 글·댓글 표시 — 트리거가 채우므로 손님이 꾸밀 수 없다.
-- 조회수는 sheet_request_view() 로만 올라간다.
-- 2026-11-05 적용

create table if not exists public.sheet_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  title text not null check (char_length(btrim(title)) between 1 and 100),
  artist text not null default '',
  kind text not null check (kind in ('acoustic', 'electric', 'fingerstyle', 'solo', 'bass', 'other')),
  body text not null default '' check (char_length(body) <= 3000),
  youtube_url text check (youtube_url is null or char_length(youtube_url) <= 300),
  status text not null default 'requested' check (status in ('requested', 'working', 'done')),
  is_notice boolean not null default false,
  by_admin boolean not null default false,
  view_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz,
  -- 공지는 가수 없이 쓸 수 있다
  constraint sheet_requests_artist_check check (char_length(artist) <= 100 and (is_notice or char_length(btrim(artist)) >= 1))
);
create index if not exists sheet_requests_created_idx on public.sheet_requests (created_at desc);
create index if not exists sheet_requests_user_idx on public.sheet_requests (user_id);

create table if not exists public.sheet_request_comments (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.sheet_requests(id) on delete cascade,
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  body text not null check (char_length(btrim(body)) between 1 and 2000),
  by_admin boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz
);
create index if not exists sheet_request_comments_req_idx on public.sheet_request_comments (request_id, created_at);
create index if not exists sheet_request_comments_user_idx on public.sheet_request_comments (user_id);

create table if not exists public.sheet_request_likes (
  request_id bigint not null references public.sheet_requests(id) on delete cascade,
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (request_id, user_id)
);
create index if not exists sheet_request_likes_user_idx on public.sheet_request_likes (user_id);

-- 글: 사이트 손님(anon/authenticated)은 작성자·운영자 표시·조회수·작성 시각을 못 바꾸고,
-- 상태·공지는 운영 계정만. SQL 편집기(postgres)에서는 그대로 둔다.
create or replace function public.sheet_requests_guard()
returns trigger language plpgsql set search_path = '' as $$
declare
  is_guest boolean := current_user in ('anon', 'authenticated');
  is_admin boolean := public.is_site_admin();
begin
  if tg_op = 'INSERT' then
    if is_guest then
      new.by_admin := is_admin;
      new.view_count := 0;
      new.created_at := now();
      if not is_admin then
        new.status := 'requested';
        new.is_notice := false;
      end if;
    end if;
    new.updated_at := null;
  else
    if is_guest then
      new.id := old.id;
      new.user_id := old.user_id;
      new.by_admin := old.by_admin;
      new.view_count := old.view_count;
      new.created_at := old.created_at;
      if not is_admin and (new.status is distinct from old.status or new.is_notice is distinct from old.is_notice) then
        raise exception '글 상태와 공지는 운영자만 바꿀 수 있어요' using errcode = '42501';
      end if;
    end if;
    if (new.title, new.artist, new.kind, new.body, new.youtube_url)
       is distinct from (old.title, old.artist, old.kind, old.body, old.youtube_url) then
      new.updated_at := now();
    else
      new.updated_at := old.updated_at;
    end if;
  end if;
  return new;
end $$;

drop trigger if exists sheet_requests_guard on public.sheet_requests;
create trigger sheet_requests_guard before insert or update on public.sheet_requests
  for each row execute function public.sheet_requests_guard();

-- 댓글: 어느 글의 댓글인지·작성자·운영자 표시는 못 바꾸게
create or replace function public.sheet_request_comments_guard()
returns trigger language plpgsql set search_path = '' as $$
declare
  is_guest boolean := current_user in ('anon', 'authenticated');
begin
  if tg_op = 'INSERT' then
    if is_guest then
      new.by_admin := public.is_site_admin();
      new.created_at := now();
    end if;
    new.updated_at := null;
  else
    if is_guest then
      new.id := old.id;
      new.request_id := old.request_id;
      new.user_id := old.user_id;
      new.by_admin := old.by_admin;
      new.created_at := old.created_at;
    end if;
    new.updated_at := case when new.body is distinct from old.body then now() else old.updated_at end;
  end if;
  return new;
end $$;

drop trigger if exists sheet_request_comments_guard on public.sheet_request_comments;
create trigger sheet_request_comments_guard before insert or update on public.sheet_request_comments
  for each row execute function public.sheet_request_comments_guard();

-- 조회수 +1 (글 보기를 열 때 한 번)
create or replace function public.sheet_request_view(p_id bigint)
returns integer language sql security definer set search_path = '' as $$
  update public.sheet_requests set view_count = view_count + 1 where id = p_id returning view_count;
$$;
revoke all on function public.sheet_request_view(bigint) from public;
grant execute on function public.sheet_request_view(bigint) to anon, authenticated;

